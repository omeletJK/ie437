/* ============================================================
   widget: conservative-coms                        (Chapter 5, Act 2)
   The same fifteen points — only the training loss and the search change.
   Conservative Objective Models are trained here for real: at each round
   the adversarial set mu(x) is regenerated by 25 plain ascent steps on the
   *current* surrogate from every data point, and the surrogate is refitted
   with the penalty  alpha ( E_mu[f] - E_D[f] ).

   The final search is the paper's Algorithm 2: trust-region ascent from the
   best design in D,
        x <- x + eta * d/dx [ fh(x) - beta * fh(x + eta * fh'(x)) ],
   beta = 0.9, T = 450 steps (Trabucco et al., 2021, Eq. 4). The dial uses
   this search at EVERY alpha, so it isolates the training penalty; the
   naive method (plain fit, plain ascent) is drawn only as a reference.

   All three modes draw ONE figure, the one students met in Act 1
   (surrogate-exploit, mode "bound"): the design axis, the faint truth, the
   surrogate dashed, a choice x̂ as a dot where the surrogate puts it and a
   ring where the truth does, B between them (red when over-promised), A at
   x* in amber; plus the attacker's region mu on the floor, the start (□)
   and a key in the top-left corner. No second panel, no search-step axis.
   mode "dial"      (default) drag alpha; the readout is Act 1's: x̂,
                    promised, real, B = fh(xh) - f(xh), A = f(x*) - fh(x*), loss.
   mode "optimiser" alpha fixed (0.3); the arrow key adds plain ascent on the
                    same conservative surrogate, then the trust region on the
                    unpenalised fit — the 2 x 2 of model and search:
                                    plain ascent        trust region
                      alpha 0       x 10.00, f -0.14    x 10.00, f -0.14
                      alpha 0.3     x 10.00, f -0.14    x  6.32, f  2.62
                    In this toy neither half works alone.
   mode "first"     alpha fixed (0.3): the source's first attempt, alpha E_mu[f]
                    with no data term. Red lines mark the data above it:
                    14 of 15 points sit above the surface fitted to them (mean
                    error on D exactly -alpha). The arrow key adds full COMs —
                    in this toy the same curve lifted by alpha, since the data
                    term's gradient lies along the constant feature. No search
                    is drawn: Algorithm 2 comes two slides later.

   Verified in node (seed 17):
     alpha 0     TR      xh 10.00  f -0.14   A -0.03  B  4.44  loss 2.79
                 (passes 2.66 near step 50, at the edge by step 450)
     alpha 0.15  TR      xh  6.93  f  2.32   A  0.52  B -0.10  loss 0.33
     alpha 0.30  TR      xh  6.32  f  2.62   A  0.67  B -0.62  loss 0.03
     alpha 0.45  TR      xh  6.06  f  2.66                      loss 0.00
     alpha 1.30  TR      xh  4.42  f  1.96   A  1.41  B -0.28  loss 0.70
   At alpha 0.3, plain ascent passes 6.20 (worth 2.65) near step 40 and
   reaches the far edge x = 10 (fh 2.31, f -0.14) by step ~150: the
   conservative surrogate still over-rates the region its attacker never
   visited, and only the slow search — given its fixed 450 steps — does not
   get there. It is not run to convergence: L_opt's gradient is about
   0.1 * fh', so each step moves ~0.0024 and 450 steps travel ~1.1. Run
   longer (alpha 0.3): x 7.41 at 900 steps (f 1.90), 9.78 at 1,800, the
   edge by 4,500. Only alpha 1.3 stops at a real peak of the surrogate
   (x 4.43). The attacker's farthest point at alpha 0.3 is x 5.84.
   With a 1-step attacker (the paper's implementation) this 1-D toy is too
   local to protect anything; the toy uses 25 steps and says so.
   ============================================================ */
IE437.widget('conservative-coms', function (host, opts) {
  var E = IE437.el, INK = '#16181D', BLUE = '#2563EB', GREEN = '#16A34A',
      RED = '#D64545', SLATE = '#64748B', AMBER = '#B45309';
  var MODE = (opts.mode === 'optimiser' || opts.mode === 'global') ? 'optimiser' : opts.mode === 'first' ? 'first' : 'dial';

  var X0 = 0, X1 = 10, DL = 0.8, DR = 5.4, LAM = 0.06, ETA = 0.35, TMAX = 40, N = 15;
  var ROUNDS = 40, MSTEP = 25, DAMP = 0.25;
  var ALPHA = [0, 0.15, 0.3, 0.45, 0.6, 0.9, 1.3];
  var AI0 = MODE === 'dial' ? 0 : 2, ai = AI0;
  var TS = 450, BETA = 0.9;                          /* the paper's Algorithm 2 */
  if (typeof opts.alpha === 'number') { var hit = ALPHA.indexOf(opts.alpha); if (hit >= 0) ai = AI0 = hit; }

  function ftrue(x) {
    return 2.55 * Math.exp(-0.5 * Math.pow((x - 6.1) / 1.75, 2))
         + 0.95 * Math.exp(-0.5 * Math.pow((x - 2.3) / 1.30, 2))
         - 0.55 * Math.exp(-0.5 * Math.pow((x - 9.3) / 1.10, 2)) + 0.10;
  }
  var KN = [], MK = 26, j;
  for (j = 0; j < MK; j++) KN.push(0.35 + 9.3 * j / (MK - 1));
  function phi(x) {
    var v = [1, x / 5], k;
    for (k = 0; k < MK; k++) { v.push(Math.max(0, x - KN[k]) / 3); v.push(Math.max(0, KN[k] - x) / 3); }
    return v;
  }
  var P = phi(0).length;
  function solve(A, b) {
    var n = b.length, M = A.map(function (r, i) { return r.concat([b[i]]); }), c, r, k, p, d, f, t;
    for (c = 0; c < n; c++) {
      p = c; for (r = c + 1; r < n; r++) if (Math.abs(M[r][c]) > Math.abs(M[p][c])) p = r;
      t = M[c]; M[c] = M[p]; M[p] = t;
      d = M[c][c]; for (k = c; k <= n; k++) M[c][k] /= d;
      for (r = 0; r < n; r++) { if (r === c) continue; f = M[r][c]; if (!f) continue;
        for (k = c; k <= n; k++) M[r][k] -= f * M[c][k]; }
    }
    return M.map(function (row) { return row[n]; });
  }

  var R = IE437.rng(opts.seed || 17), D = [], i, q;
  for (i = 0; i < N; i++) {
    var xi = DL + (DR - DL) * (i + 0.5 + 0.55 * (R() - 0.5)) / N;
    D.push({ x: xi, y: ftrue(xi) + 0.045 * (R() * 2 - 1) });
  }
  var GA = [], gb = new Array(P), dbar = new Array(P);
  for (i = 0; i < P; i++) { gb[i] = 0; dbar[i] = 0; GA.push(new Array(P)); for (q = 0; q < P; q++) GA[i][q] = 0; }
  D.forEach(function (d) {
    var p = phi(d.x);
    for (var a = 0; a < P; a++) { gb[a] += p[a] * d.y / N; dbar[a] += p[a] / N;
      for (var c = 0; c < P; c++) GA[a][c] += p[a] * p[c] / N; }
  });
  for (i = 0; i < P; i++) GA[i][i] += (i < 2 ? LAM * 1e-2 : LAM);

  function ev(w, x) { var p = phi(x), s = 0; for (var a = 0; a < P; a++) s += w[a] * p[a]; return s; }
  function grad(w, x) { return (ev(w, x + 1e-4) - ev(w, x - 1e-4)) / 2e-4; }
  function ascend(w, xs, steps) {
    var path = [xs], x = xs;
    for (var t = 0; t < steps; t++) { x = Math.max(X0, Math.min(X1, x + ETA * grad(w, x))); path.push(x); }
    return path;
  }
  function attack(w) {                              /* mu: every point the attacker visits */
    var m = [];
    D.forEach(function (d) { var pp = ascend(w, d.x, MSTEP); for (var t = 1; t < pp.length; t++) m.push(pp[t]); });
    return m;
  }
  function clip(x) { return Math.max(X0, Math.min(X1, x)); }
  function trPath(w, xs) {                          /* Eq. 4: penalise the lookahead iterate */
    var L = function (z) { return ev(w, z) - BETA * ev(w, clip(z + ETA * grad(w, z))); };
    var path = [xs], x = xs;
    for (var t = 0; t < TS; t++) { x = clip(x + ETA * (L(x + 1e-4) - L(x - 1e-4)) / 2e-4); path.push(x); }
    return path;
  }
  var PCACHE = {};
  function search(a) {                              /* Algorithm 2 at every alpha */
    if (PCACHE[a]) return PCACHE[a];
    return (PCACHE[a] = trPath(model(a), x0));
  }

  var CACHE = {};
  var CACHE1 = {};
  function model1(a) {                              /* the source's first attempt: no data term */
    if (CACHE1[a]) return CACHE1[a];
    var w = solve(GA, gb), r, k, m, mb, wn;
    for (r = 0; r < ROUNDS; r++) {
      m = [];
      D.forEach(function (d) { var pp = ascend(w, d.x, MSTEP); for (var t = 1; t < pp.length; t++) m.push(pp[t]); });
      mb = new Array(P); for (k = 0; k < P; k++) mb[k] = 0;
      m.forEach(function (x) { var pp = phi(x); for (var c = 0; c < P; c++) mb[c] += pp[c] / m.length; });
      wn = solve(GA, gb.map(function (v, c) { return v - a * mb[c]; }));
      for (k = 0; k < P; k++) w[k] = (1 - DAMP) * w[k] + DAMP * wn[k];
    }
    return (CACHE1[a] = w);
  }
  function model(a) {
    if (CACHE[a]) return CACHE[a];
    var w = solve(GA, gb), r, k, m, mb, wn, rhs;
    if (a > 0) {
      for (r = 0; r < ROUNDS; r++) {
        m = [];
        D.forEach(function (d) { var pp = ascend(w, d.x, MSTEP); for (var t = 1; t < pp.length; t++) m.push(pp[t]); });
        mb = new Array(P); for (k = 0; k < P; k++) mb[k] = 0;
        m.forEach(function (x) { var pp = phi(x); for (var c = 0; c < P; c++) mb[c] += pp[c] / m.length; });
        rhs = gb.map(function (v, c) { return v - a * (mb[c] - dbar[c]); });
        wn = solve(GA, rhs);
        for (k = 0; k < P; k++) w[k] = (1 - DAMP) * w[k] + DAMP * wn[k];
      }
    }
    return (CACHE[a] = w);
  }

  var W0 = model(0);
  var x0 = D[0].x, y0 = D[0].y;
  D.forEach(function (d) { if (d.y > y0) { y0 = d.y; x0 = d.x; } });
  var PATH0 = ascend(W0, x0, TS);
  var XS = 0, FS = -1e9;
  for (i = 0; i <= 4000; i++) { var xg = X0 + (X1 - X0) * i / 4000; if (ftrue(xg) > FS) { FS = ftrue(xg); XS = xg; } }
  var YLO = -0.7, YHI = 4.8, MONO = 'IBM Plex Mono, monospace';
  function f2(v) { var s = Math.abs(v).toFixed(2); return (v < 0 && +s ? '−' : '') + s; }

  var bar = MODE === 'dial'
    ? '<div class="wbar"><span class="wt">Conservatism, dialled</span><span class="wspacer"></span>' +
      '<span class="wlabel">conservatism</span><span class="wnum" data-a></span><span data-sl></span></div>'
    : MODE === 'first'
    ? '<div class="wbar"><span class="wt">Push the attacker down — with and without holding the data up</span><span class="wspacer"></span>' +
      '<span class="wlabel">penalty</span><span class="wnum">α = 0.30</span></div>'
    : '<div class="wbar"><span class="wt">The same conservative surrogate, two searches</span><span class="wspacer"></span>' +
      '<span class="wlabel">search</span><span class="wnum">α = 0.30 · 450 steps</span></div>';
  /* One figure for all three modes, and it is Act 1's ("Where the loss comes
     from", surrogate-exploit mode "bound"): the design axis, the faint truth,
     the surrogate dashed, a choice x̂ as a dot on the surrogate with a line down
     to a ring on the truth — plus the attacker's region on the floor. */
  host.innerHTML = bar +
    '<div class="wbody" style="flex-direction:row;gap:18px;align-items:flex-start;justify-content:center">' +
    '<div data-c1></div>' +
    '<div style="width:250px;display:flex;flex-direction:column;gap:9px">' +
    '<div data-num style="font:400 12.5px/1.8 var(--sans);color:var(--ink2)"></div>' +
    '<div data-note style="font:400 11.5px/1.55 var(--sans);color:var(--ink3);' +
    'border-top:1px solid rgba(22,24,29,.075);padding-top:9px"></div></div></div>';

  var CW = 640, CH = 300, s1 = IE437.svg(CW, CH);
  host.querySelector('[data-c1]').appendChild(s1);
  var stage = 0;

  function frame() {
    while (s1.firstChild) s1.removeChild(s1.firstChild);
    var L = 34, Rr = 118, T = 16, B = 30;
    var PX = function (v) { return L + (v - X0) / (X1 - X0) * (CW - L - Rr); };
    var PY = function (v) { return CH - B - (v - YLO) / (YHI - YLO) * (CH - T - B); };
    E('rect', { x: PX(DL), y: T, width: PX(DR) - PX(DL), height: CH - B - T, fill: SLATE, 'fill-opacity': .09 }, s1);
    E('text', { x: PX(DR) - 6, y: T + 12, 'text-anchor': 'end', 'font-size': 9,
      'font-family': MONO, fill: INK, 'fill-opacity': .45, text: 'the dataset D' }, s1);
    E('text', { x: (PX(DR) + PX(X1)) / 2, y: T + 12, 'text-anchor': 'middle', 'font-size': 9,
      'font-family': MONO, fill: INK, 'fill-opacity': .3, text: 'no data' }, s1);
    E('line', { x1: L, x2: CW - Rr, y1: PY(0), y2: PY(0), stroke: INK, 'stroke-opacity': .22 }, s1);
    E('line', { x1: L, x2: L, y1: T, y2: CH - B, stroke: INK, 'stroke-opacity': .28 }, s1);
    [0, 2, 4].forEach(function (v) {
      E('text', { x: L - 5, y: PY(v) + 3.2, 'text-anchor': 'end', 'font-size': 9, fill: INK,
        'fill-opacity': .45, 'font-family': MONO, text: v }, s1);
    });
    E('text', { x: L + (CW - L - Rr) / 2, y: CH - 5, 'text-anchor': 'middle', 'font-size': 9.5,
      'font-style': 'italic', fill: INK, 'fill-opacity': .45, text: 'x' }, s1);
    var g = { PX: PX, PY: PY };
    curve(g, ftrue, INK, '', 2.2, .34);
    return g;
  }
  function curve(g, fn, col, dash, w, op) {
    var pts = [], k;
    for (k = 0; k <= 300; k++) { var x = X0 + (X1 - X0) * k / 300; pts.push(g.PX(x).toFixed(1) + ' ' + g.PY(fn(x)).toFixed(1)); }
    E('path', { d: 'M' + pts.join('L'), fill: 'none', stroke: col, 'stroke-width': w,
      'stroke-dasharray': dash, 'stroke-opacity': op == null ? 1 : op, 'stroke-linejoin': 'round' }, s1);
  }
  function surrogate(g, w, col, op) {
    curve(g, function (x) { return ev(w, x); }, col, '5 3', 2.2, op);
  }
  /* the key: the same corner on all three slides, so no label ever lands on a curve */
  function key(g, items) {
    var x = g.PX(0.15), y = g.PY(4.45);
    [{ col: INK, op: .34, lab: 'true f — never queried', solid: true }].concat(items).forEach(function (it, q) {
      var yy = y + 15 * q, op = it.op == null ? 1 : it.op;
      if (it.sq) E('rect', { x: x + 5.5, y: yy - 7, width: 7, height: 7, fill: '#FAFAF8', stroke: INK, 'stroke-width': 1.6 }, s1);
      else E('line', { x1: x, x2: x + 18, y1: yy - 3.5, y2: yy - 3.5, stroke: it.col, 'stroke-width': 2.2,
        'stroke-dasharray': it.solid ? '' : '5 3', 'stroke-opacity': op }, s1);
      E('text', { x: x + 24, y: yy, 'font-size': 10.5, fill: it.col, 'fill-opacity': Math.max(.55, op), 'font-weight': 700, text: it.lab }, s1);
    });
  }
  function dots(g) {
    D.forEach(function (d) { E('circle', { cx: g.PX(d.x), cy: g.PY(d.y), r: 2.9, fill: INK }, s1); });
  }
  /* where the attacker went: mu as a histogram on the floor of the chart */
  function strip(sv, PX, y0, mu, lo, hi) {
    var HB = 0.25, n = Math.round((X1 - X0) / HB), hist = [], top = 0, b;
    for (b = 0; b < n; b++) hist.push(0);
    mu.forEach(function (x) { hist[Math.min(n - 1, Math.floor((x - X0) / HB))]++; });
    hist.forEach(function (c) { top = Math.max(top, c); });
    hist.forEach(function (c, b) {
      var xa = Math.max(lo, X0 + b * HB), xb = Math.min(hi, X0 + (b + 1) * HB), h = 20 * c / top;
      if (c && xb > xa) E('rect', { x: PX(xa) + 0.5, y: y0 - h, width: PX(xb) - PX(xa) - 1, height: h, fill: INK, 'fill-opacity': .24 }, sv);
    });
  }
  function floorMu(g, w) {
    var MU = attack(w), mx = Math.max.apply(null, MU);
    strip(s1, g.PX, g.PY(YLO), MU, X0, X1);
    E('text', { x: g.PX(mx) + 6, y: g.PY(YLO) - 4, 'font-size': 9, 'font-family': MONO, fill: INK,
      'fill-opacity': .55, text: 'where the attacker went (μ)' }, s1);
  }
  /* the stretch of surrogate a search slid along, from the start */
  function travel(g, w, xb, col, wid) {
    var pts = [], k, lo = Math.min(x0, xb), hi = Math.max(x0, xb);
    for (k = 0; k <= 80; k++) { var x = lo + (hi - lo) * k / 80; pts.push(g.PX(x).toFixed(1) + ' ' + g.PY(ev(w, x)).toFixed(1)); }
    E('path', { d: 'M' + pts.join('L'), fill: 'none', stroke: col, 'stroke-width': wid || 7, 'stroke-opacity': .22, 'stroke-linecap': 'round' }, s1);
  }
  function start(g, w) {
    var x = g.PX(x0), y = g.PY(ev(w, x0));
    E('rect', { x: x - 3.5, y: y - 3.5, width: 7, height: 7, fill: '#FAFAF8', stroke: INK, 'stroke-width': 1.6 }, s1);
  }
  /* a choice, as in Act 1: a dot where the surrogate puts it, a ring where the
     truth puts it, and B between them — red when the surrogate over-promises */
  function choice(g, w, x, col, lab, showB) {
    var yp = g.PY(ev(w, x)), yr = g.PY(ftrue(x)), over = ev(w, x) > ftrue(x);
    E('line', { x1: g.PX(x), y1: yp, x2: g.PX(x), y2: yr, stroke: over ? RED : GREEN, 'stroke-width': 3, 'stroke-opacity': .85 }, s1);
    E('circle', { cx: g.PX(x), cy: yr, r: 4.5, fill: '#FAFAF8', stroke: INK, 'stroke-width': 2 }, s1);
    E('circle', { cx: g.PX(x), cy: yp, r: 5.5, fill: col }, s1);
    if (lab) E('text', { x: g.PX(x) + 9, y: yp + 17, 'font-size': 10.5, fill: col, 'font-weight': 700, text: lab }, s1);
    if (showB && Math.abs(yr - yp) > 22) E('text', { x: g.PX(x) + 8, y: (yp + yr) / 2 + 4,
      'font-size': 13, fill: over ? RED : GREEN, 'font-weight': 700, text: 'B' }, s1);
  }
  function optimum(g, w, showA) {
    E('circle', { cx: g.PX(XS), cy: g.PY(FS), r: 5, fill: INK }, s1);
    E('text', { x: g.PX(XS) - 10, y: g.PY(FS) - 14, 'text-anchor': 'end', 'font-size': 11, fill: INK,
      'font-weight': 700, text: 'x* — the true optimum' }, s1);
    if (showA && FS - ev(w, XS) > 0.3) {                     /* A, when the surrogate under-rates x* */
      E('line', { x1: g.PX(XS) - 9, y1: g.PY(FS), x2: g.PX(XS) - 9, y2: g.PY(ev(w, XS)), stroke: AMBER, 'stroke-width': 3 }, s1);
      E('text', { x: g.PX(XS) - 15, y: (g.PY(FS) + g.PY(ev(w, XS))) / 2 + 4, 'text-anchor': 'end', 'font-size': 13, fill: AMBER, 'font-weight': 700, text: 'A' }, s1);
    }
  }
  /* did the search stop because its steps ran out, not at a peak? */
  function stillRising(w, x) {
    return x < X1 - 0.3 && (ev(w, x + 1e-3) - ev(w, x - 1e-3)) / 2e-3 > 0.01;
  }
  var row = function (lab, val, c, on) {
    return '<div style="display:flex;justify-content:space-between;opacity:' + (on === false ? .28 : 1) + '"><span>' + lab + '</span>' +
      '<b style="color:' + (c || INK) + ';font-family:var(--mono)">' + (on === false ? '—' : val) + '</b></div>';
  };
  var rule = '<div style="border-top:1px solid rgba(22,24,29,.12);margin:4px 0"></div>';

  function drawFirst() {
    var a = ALPHA[ai], W1 = model1(a), W = model(a);
    var res = function (w) { var s = 0; D.forEach(function (d) { s += ev(w, d.x) - d.y; }); return s / N; };
    var above = D.filter(function (d) { return d.y > ev(W1, d.x); }).length;
    var g = frame();
    floorMu(g, W1);                     /* the same for both fits: they differ by a constant */
    surrogate(g, W0, BLUE, .4);
    surrogate(g, W1, RED, stage >= 1 ? .45 : 1);
    if (stage >= 1) surrogate(g, W, GREEN);
    key(g, [{ col: BLUE, op: .4, lab: 'plain fit' }, { col: RED, op: stage >= 1 ? .45 : 1, lab: 'first attempt' }]
      .concat(stage >= 1 ? [{ col: GREEN, lab: 'full COMs' }] : []));
    D.forEach(function (d) {            /* the data sit above the first attempt */
      E('line', { x1: g.PX(d.x), x2: g.PX(d.x), y1: g.PY(d.y), y2: g.PY(ev(W1, d.x)), stroke: RED,
        'stroke-opacity': stage >= 1 ? .3 : .7, 'stroke-width': 2 }, s1);
    });
    dots(g);
    host.querySelector('[data-num]').innerHTML =
      '<div style="font-size:11px;color:var(--ink3)">model − data, mean on D</div>' +
      row('<span style="color:' + RED + '">first attempt</span>', f2(res(W1)), RED) +
      row('<span style="color:' + GREEN + '">full COMs</span>', f2(res(W)), GREEN, stage >= 1) + rule +
      row('points above the first attempt', above + ' / ' + N, INK);
    host.querySelector('[data-note]').innerHTML = stage === 0
      ? 'The whole surface sinks below the data it was fitted to. Sinking everything by c cuts the penalty by αc and costs the fit only ½c², so it sinks by α. Press &rarr; for the fix.'
      : 'Holding the data up lifts it back by α: a shift moves E<sub>μ</sub>[f] and E<sub>D</sub>[f] alike, so sinking no longer pays. The push stays where the attacker went.';
  }

  function drawDial() {
    var a = ALPHA[ai], W = model(a), xh = search(a)[TS], col = a > 0 ? GREEN : BLUE;
    var g = frame();
    if (a > 0) { floorMu(g, W); surrogate(g, W0, BLUE, .3); }
    surrogate(g, W, col);
    key(g, (a > 0 ? [{ col: BLUE, op: .3, lab: 'plain fit' }, { col: GREEN, lab: 'conservative fθ' }]
      : [{ col: BLUE, lab: 'plain fit — no penalty' }]).concat([{ sq: true, col: INK, lab: 'start: the best design in D' }]));
    dots(g);
    travel(g, W, xh, col);
    start(g, W);
    optimum(g, W, true);
    var rising = stillRising(W, xh);
    choice(g, W, xh, col, 'x̂', true);
    var vA = FS - ev(W, XS), vB = ev(W, xh) - ftrue(xh), loss = FS - ftrue(xh);
    host.querySelector('[data-a]').textContent = 'α = ' + a.toFixed(2);
    host.querySelector('[data-num]').innerHTML =
      row('x̂ — where the search stopped', xh.toFixed(2)) +
      row('promised f̂(x̂)', f2(ev(W, xh)), col) +
      row('real f(x̂)', f2(ftrue(xh))) + rule +
      row('B = f̂(x̂) − f(x̂)', f2(vB), vB > 0 ? RED : GREEN) +
      row('A = f(x*) − f̂(x*)', f2(vA), AMBER) +
      row('loss = f(x*) − f(x̂)', f2(loss), loss > 0.3 ? RED : INK);
    host.querySelector('[data-note]').innerHTML =
      a === 0 ? '<b>No penalty.</b> The surrogate rises past the data, and even the slow search reaches the edge: B is huge.'
      : vA > 1 ? '<b>Too much.</b> Flattened so far that the search stops at a peak inside the data; A is huge.'
      : loss < 0.05 ? '<b>About right.</b> B is negative and the loss is near zero. The search stops at x̂ only because its 450 steps run out' + (rising ? ' — the surrogate still rises beyond it.' : '.')
      : '<b>Not enough.</b> Flatter, but 450 slow steps still carry the search past x*.';
  }

  function drawOptimiser() {
    var a = ALPHA[ai], W = model(a), xt = search(a)[TS], xp = ascend(W, x0, TS)[TS], xz = trPath(W0, x0)[TS];
    var g = frame();
    floorMu(g, W);
    surrogate(g, W0, BLUE, stage >= 2 ? 1 : .3);
    surrogate(g, W, GREEN);
    key(g, [{ col: BLUE, op: stage >= 2 ? 1 : .3, lab: 'plain fit' }, { col: GREEN, lab: 'conservative fθ' },
      { sq: true, col: INK, lab: 'start: the best design in D' }]);
    dots(g);
    if (stage >= 2) travel(g, W0, xz, BLUE, 5);
    if (stage >= 1) travel(g, W, xp, INK, 5);
    travel(g, W, xt, GREEN, 8);
    start(g, W);
    optimum(g, W, false);
    if (stage >= 2) choice(g, W0, xz, BLUE, 'slow search');
    if (stage >= 1) choice(g, W, xp, GREEN, 'plain ascent');
    choice(g, W, xt, GREEN, 'slow search');
    var pr = function (w, x) { return f2(ev(w, x)) + ' → ' + f2(ftrue(x)); };
    host.querySelector('[data-num]').innerHTML =
      '<div style="font-size:11px;color:var(--ink3);text-align:right">promised → real</div>' +
      row('<span style="color:' + GREEN + '">slow search</span>', pr(W, xt), INK) +
      row('<span style="color:' + GREEN + '">plain ascent</span>', pr(W, xp), RED, stage >= 1) +
      row('<span style="color:' + BLUE + '">slow search, plain fit</span>', pr(W0, xz), RED, stage >= 2);
    host.querySelector('[data-note]').innerHTML = stage === 0
      ? 'The slow search on the conservative surrogate: when its 450 steps run out it is next to x*, though the surrogate still rises beyond it. Press &rarr; for plain ascent on the same surrogate.'
      : stage === 1
      ? 'Plain ascent takes full steps and runs to the edge, where the attacker never went — nothing pushed the surrogate down there. Press &rarr; again.'
      : 'The slow search on the plain fit reaches the edge too. <b>It takes both</b>: a flattened surrogate and a short, slow search.';
  }

  var draw = MODE === 'dial' ? drawDial : MODE === 'first' ? drawFirst : drawOptimiser;
  var dial = null;
  if (MODE === 'dial') {
    dial = IE437.slider(host.querySelector('[data-sl]'), {
      bare: true, min: 0, max: ALPHA.length - 1, step: 1, value: ai,
      on: function (v) { ai = v; draw(); }
    });
  }
  draw();

  if (MODE === 'dial') {
    return {
      reset: function () { ai = AI0; dial.set(AI0, false); draw(); },
      finish: function () { ai = 2; dial.set(2, false); draw(); }
    };
  }
  var NST = MODE === 'optimiser' ? 2 : 1;
  var show = function (i) { stage = Math.max(0, Math.min(NST, i)); draw(); };
  return { steps: NST, step: show, reset: function () { show(0); }, finish: function () { show(NST); } };
});
